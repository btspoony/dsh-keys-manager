/**
 * Generate the Google OAuth client facts for the two routes from the pinned omp
 * catalog.
 *
 * The client id and secret are Google's *public installed-app* credentials,
 * copied into omp's MIT sources; they are not user secrets. GitHub's push
 * protection cannot tell the difference and blocks the branch, so they must not
 * live in tracked source: this script derives them from the pin at build time
 * and writes an ignored module the routes import.
 *
 * The parse mirrors what the pinned rules declare: both values are `base64`
 * encoded in the KDL (`client-id "…" encoding="base64"`), so decode before
 * emitting. The output is deterministic — no timestamp, fixed order — so
 * regenerating an unchanged pin is a byte-identical file.
 *
 * @module dsh-llm-omp-transports/generate-google-client-facts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const packageRoot = dirname(scriptsDir)

/** Resolve the installed root of a package by walking up to its own manifest. */
function packageRootOf(name) {
  let dir = dirname(fileURLToPath(import.meta.resolve(name)))
  while (dir !== dirname(dir)) {
    const manifestPath = join(dir, 'package.json')
    if (existsSync(manifestPath)) {
      const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
      if (manifest.name === name) return dir
    }
    dir = dirname(dir)
  }
  throw new Error(`cannot locate the installed root of ${name}`)
}

/** The routes whose auth rule carries a Google OAuth client. */
const ROUTES = ['google-gemini-cli', 'google-antigravity']

const rulesDir = join(packageRootOf('@oh-my-pi/pi-catalog'), 'src', 'compat', 'rules', 'auth')

/** One rule's decoded client, read exactly as the rule declares it. */
function clientFacts(route) {
  const rulePath = join(rulesDir, `${route}.kdl`)
  const rule = readFileSync(rulePath, 'utf8')
  const read = name => {
    const match = new RegExp(`${name}\\s+"([^"]+)"\\s+encoding="base64"`).exec(rule)
    if (match === null) throw new Error(`${rulePath}: no base64 "${name}"`)
    return Buffer.from(match[1], 'base64').toString('utf8')
  }
  return { clientId: read('client-id'), clientSecret: read('client-secret') }
}

const facts = Object.fromEntries(ROUTES.map(route => [route, clientFacts(route)]))

const body = `/**
 * Generated by \`scripts/generate-google-client-facts.mjs\` from the pinned
 * \`@oh-my-pi/pi-catalog\` auth rules. Do not commit this file and do not edit it:
 * GitHub push protection treats Google's installed-app client values as secrets,
 * so they are derived at build time and the module stays ignored.
 */
/** The OAuth client one route's pinned rule declares. */
export interface GoogleClientFacts {
  readonly clientId: string
  readonly clientSecret: string
}

/** The pinned client identity per route. */
export const GOOGLE_CLIENT_FACTS: Readonly<
  Record<'google-gemini-cli' | 'google-antigravity', GoogleClientFacts>
> = ${JSON.stringify(
  facts,
  null,
  2,
)}
`

const outPath = join(packageRoot, 'src', 'google', 'client-facts.generated.ts')
writeFileSync(outPath, body)
console.log(`google client facts: ${ROUTES.join(', ')} -> ${outPath}`)
