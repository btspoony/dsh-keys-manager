/**
 * Bundle the browser half into the module-loader artifact the DSH Web client
 * executes.
 *
 * The source is a normal ESM TypeScript entry; esbuild emits CommonJS and the
 * banner/footer wrap it in the loader's closure factory. React stays external
 * because the browser module table provides it. Host and DSH packages must
 * never appear as runtime imports: the Client half is rendered inside the
 * harness, so only React is loaded from the module table.
 */
import { build } from 'esbuild'
import { readFile } from 'node:fs/promises'

const ID = 'dsh-keys-manager'
const OUT = 'lib/client.js'

const result = await build({
  entryPoints: ['src/client/index.ts'],
  outfile: OUT,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', 'react/jsx-runtime'],
  sourcemap: false,
  logLevel: 'warning',
  banner: {
    js: [
      '/* Keys Manager Client bundle; generated by scripts/build-client.mjs. */',
      `window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}, factory: (require) => {`,
      'var module = { exports: {} }; var exports = module.exports;',
    ].join('\n'),
  },
  footer: {
    js: 'return module.exports; } });',
  },
})

if (result.errors.length > 0) {
  throw new Error(`client bundle build failed:\n${result.errors.map(error => error.text).join('\n')}`)
}

const text = await readFile(OUT, 'utf8')
if (!text.includes(`window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}`)) {
  throw new Error('client bundle is missing the module-loader handoff')
}
if (text.includes('import.meta')) {
  throw new Error('client bundle must not contain import.meta; the loader executes it as a classic script')
}
if (/require\(["']@deepseek-ai\//.test(text)) {
  throw new Error('client bundle must not require @deepseek-ai packages at runtime')
}
console.log(`built ${OUT} (${Buffer.byteLength(text)} bytes)`)
